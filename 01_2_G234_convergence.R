#
# Direction is defined across G2/G3/G4:
#   Up         = log2FC > 0 in all three groups
#   Down       = log2FC < 0 in all three groups
#   Discordant = mixed directions across the three groups
#
# IMPORTANT:
# Direction is used ONLY for point colour. No gene is removed before
# correlation calculation.
# -----------------------------------------------------------------------------

