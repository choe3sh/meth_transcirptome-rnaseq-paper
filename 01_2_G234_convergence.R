# -----------------------------------------------------------------------------
# 4. Pairwise correlation helper
# -----------------------------------------------------------------------------

pair_defs <- tibble::tribble(
  ~comparison, ~x_group, ~y_group,
  "G2 vs G3", "G2", "G3",
  "G2 vs G4", "G2", "G4",
  "G3 vs G4", "G3", "G4"
)

make_pairwise_long <- function(df) {

  bind_rows(
    lapply(seq_len(nrow(pair_defs)), function(i) {

      xg <- pair_defs$x_group[i]
      yg <- pair_defs$y_group[i]

      tibble(
        gene         = df$gene,
        human_symbol = df$human_symbol,
        comparison   = pair_defs$comparison[i],
        x_group      = xg,
        y_group      = yg,
        x            = df[[paste0("log2FC_", xg)]],
        y            = df[[paste0("log2FC_", yg)]]
      )
    })
  ) %>%
    mutate(
      comparison = factor(
        comparison,
        levels = pair_defs$comparison
      )
    )
}

calc_correlations <- function(long_df, analysis_set) {

  long_df %>%
    group_by(comparison, x_group, y_group) %>%
    summarise(
      n = sum(is.finite(x) & is.finite(y)),
      pearson_r = cor(
        x,
        y,
        method = "pearson",
        use = "complete.obs"
      ),
      spearman_rho = cor(
        x,
        y,
        method = "spearman",
        use = "complete.obs"
      ),
      .groups = "drop"
    ) %>%
    mutate(
      analysis_set = analysis_set,
      label = sprintf(
        "r = %.2f\n\u03c1 = %.2f",
        pearson_r,
        spearman_rho
      )
    )
}

# -----------------------------------------------------------------------------
# 5. Plot helper
# -----------------------------------------------------------------------------

make_convergence_plot <- function(
    long_df,
    cor_tbl,
    point_alpha,
    point_size,
    x_limits = NULL,
    y_limits = NULL) {

  # Use common limits across all three panels.
  if (is.null(x_limits) || is.null(y_limits)) {

    vals <- c(long_df$x, long_df$y)
    vals <- vals[is.finite(vals)]

    max_abs <- max(abs(vals))

    # Round outward to a visually convenient integer.
    lim <- ceiling(max_abs)

    x_limits <- c(-lim, lim)
    y_limits <- c(-lim, lim)
  }

  label_df <- cor_tbl %>%
    mutate(
      x = x_limits[1] + 0.05 * diff(x_limits),
      y = y_limits[2] - 0.05 * diff(y_limits)
    )

  ggplot(
    long_df,
    aes(x = x, y = y)
  ) +
    geom_point(
      alpha = point_alpha,
      size = point_size
    ) +
    geom_abline(
      intercept = 0,
      slope = 1,
      linetype = "dashed",
      linewidth = 0.5
    ) +
    geom_text(
      data = label_df,
      aes(x = x, y = y, label = label),
      inherit.aes = FALSE,
      hjust = 0,
      vjust = 1,
      size = 4
    ) +
    facet_wrap(
      ~ comparison,
      nrow = 1
    ) +
    coord_cartesian(
      xlim = x_limits,
      ylim = y_limits
    ) +
    labs(
      x = expression(log[2] * "FC"),
      y = expression(log[2] * "FC")
    ) +
    theme_bw(base_size = 12) +
    theme(
      strip.background = element_rect(fill = "grey85"),
      strip.text = element_text(size = 12),
      panel.grid.minor = element_blank(),
      axis.title = element_text(size = 13)
    )
}

