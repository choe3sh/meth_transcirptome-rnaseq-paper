  mutate(
    Direction = case_when(
      log2FC_G2 > 0 & log2FC_G3 > 0 & log2FC_G4 > 0 ~ "Up",
      log2FC_G2 < 0 & log2FC_G3 < 0 & log2FC_G4 < 0 ~ "Down",
      TRUE ~ "Discordant"
    ),
    Direction = factor(
      Direction,
      levels = c("Up", "Down", "Discordant")
    )
  )

