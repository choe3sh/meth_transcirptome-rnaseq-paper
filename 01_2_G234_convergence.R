#
# Acute G2-G4 transcriptional convergence analysis
#
# Main analysis:
#   - G2-G4 shared DEG set defined in 01_1 (expected n = 321)
#   - Pairwise comparison of DESeq2 log2FC:
#       G2 vs G3, G2 vs G4, G3 vs G4
#   - Pearson r and Spearman rho
#   - No additional same-sign filtering
#
# Supplementary sensitivity analysis:
#   - All genes tested in all three G2/G3/G4 DESeq2 analyses
#   - Pairwise comparison of log2FC using the same plotting/statistical framework
#
# Input:
#   results/acute/DEG_by_AgeGroup/DEG_G2.csv
#   results/acute/DEG_by_AgeGroup/DEG_G3.csv
#   results/acute/DEG_by_AgeGroup/DEG_G4.csv
#   results/acute/DEG_by_AgeGroup/genelist_common_G234_inclusive.txt
#
# Output:
#   Main_Fig2D_G234_321_convergence.png
#   Supplementary_all_tested_genes_convergence.png
#   correlation_summary_G234_321.csv
#   G234_321_direction_counts.csv
#   correlation_summary_all_tested_genes.csv
#   G234_321_log2FC_matrix.csv
#   all_tested_genes_log2FC_matrix.csv
#
# IMPORTANT:
#   The 321-gene set is a G2-G4-convergent DEG set selected because genes are
#   significant in all three G2/G3/G4 within-group analyses. Therefore the
#   correlation within this selected set is descriptive of effect-size
#   concordance and is not an independent formal test of age-by-exposure
#   interaction.
# =============================================================================

