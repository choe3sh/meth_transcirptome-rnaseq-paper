# -----------------------------------------------------------------------------
# 2. Build a common G2/G3/G4 log2FC matrix
#
# IMPORTANT:
# "all tested genes" is defined as genes with a finite DESeq2 log2FC estimate
# in all three analyses. Genes are NOT filtered by padj for this universe.
# -----------------------------------------------------------------------------

prepare_group <- function(df, ag) {

  df %>%
    transmute(
      gene,
      human_symbol = as.character(human_symbol),
      !!paste0("log2FC_", ag) := as.numeric(log2FoldChange),
      !!paste0("padj_", ag)   := as.numeric(padj)
    )
}

g2_small <- prepare_group(g2_res, "G2")
g3_small <- prepare_group(g3_res, "G3")
g4_small <- prepare_group(g4_res, "G4")

all_common <- g2_small %>%
  full_join(
    g3_small %>% select(-human_symbol),
    by = "gene"
  ) %>%
  full_join(
    g4_small %>% select(-human_symbol),
    by = "gene"
  )

# Recover a human symbol from G3/G4 when it is absent in G2.
symbol_lookup <- bind_rows(
  g2_res %>% select(gene, human_symbol),
  g3_res %>% select(gene, human_symbol),
  g4_res %>% select(gene, human_symbol)
) %>%
  filter(!is.na(human_symbol), human_symbol != "") %>%
  distinct(gene, .keep_all = TRUE)

all_common <- all_common %>%
  select(-human_symbol) %>%
  left_join(symbol_lookup, by = "gene") %>%
  relocate(human_symbol, .after = gene)

all_tested <- all_common %>%
  filter(
    is.finite(log2FC_G2),
    is.finite(log2FC_G3),
