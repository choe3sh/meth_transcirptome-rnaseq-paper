read_deg_result <- function(ag) {

  path <- file.path(DEG_DIR, paste0("DEG_", ag, ".csv"))

  if (!file.exists(path)) {
    stop("Missing DEG result: ", path)
  }

  x <- read.csv(path, stringsAsFactors = FALSE)

  required_cols <- c(
    "gene", "human_symbol", "AgeGroup",
    "log2FoldChange", "pvalue", "padj"
  )

  missing_cols <- setdiff(required_cols, colnames(x))

  if (length(missing_cols) > 0L) {
    stop(
      sprintf(
        "%s is missing required columns: %s",
        basename(path),
        paste(missing_cols, collapse = ", ")
      )
    )
  }

  if (anyDuplicated(x$gene)) {
    stop("Duplicated gene IDs detected in ", basename(path))
  }

  x
}

